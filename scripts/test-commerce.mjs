import assert from 'node:assert/strict';
import { mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import ExcelJS from 'exceljs';
process.env.ORDER_DATABASE_PATH = join(mkdtempSync(join(tmpdir(), 'outouf-orders-test-')), 'test.sqlite');
const { savePendingOrder, attachSession, recordPaidOrder, paidOrdersForDay, copenhagenDay } = await import('../lib/commerce-orders.ts');
const { orderWorkbook } = await import('../lib/order-workbook.ts');
const order = { id: 'test-order', createdAt: '2026-10-06T20:00:00Z', status: 'pending', currency: 'DKK', subtotal: 140000, shipping: 5000, total: 145000,
  items: [{ productId: 'example', title: '=NOT_A_FORMULA()', brand: 'Example', productUrl: 'https://example.com/?product=example', size: '42', quantity: 2, unitAmount: 70000 }] };
savePendingOrder(order);
attachSession(order.id, 'test-session');
assert.equal(paidOrdersForDay('2026-10-06').length, 0);
assert.throws(() => recordPaidOrder(order.id, 'wrong-session', {}));
recordPaidOrder(order.id, 'test-session', { paidAt: '2026-10-06T22:30:00Z', email: 'example@example.com', delivery: { name: 'Test Customer', line1: 'Test address', line2: '', postalCode: '0010', city: 'Test', state: '', country: 'DK' } });
recordPaidOrder(order.id, 'test-session', { paidAt: '2026-10-08T10:00:00Z' });
assert.equal(paidOrdersForDay('2026-10-06').length, 0);
const paid = paidOrdersForDay('2026-10-07');
assert.equal(paid.length, 1);
assert.equal(copenhagenDay('2026-01-01T23:30:00Z'), '2026-01-02');
const bytes = await orderWorkbook(paid, '2026-10-07');
const book = new ExcelJS.Workbook(); await book.xlsx.load(bytes);
assert.equal(book.getWorksheet('Orders').getCell('G2').value, 1450);
assert.equal(book.getWorksheet('Items').getCell('I2').value, 1400);
assert.equal(book.getWorksheet('Items').getCell('C2').value, '=NOT_A_FORMULA()');
assert.equal(book.getWorksheet('Items').getCell('E2').value.hyperlink, 'https://example.com/?product=example');
assert.equal(book.getWorksheet('Orders').getCell('N2').value, '0010');
assert.equal(book.getWorksheet('Items').getCell('F2').value, '42');
assert.equal(book.getWorksheet('Items').getCell('G2').value, 2);
console.log('Passed: payment deduplication, session mismatch, Copenhagen dates, Excel totals, sizes, quantities, links and literal customer text.');
